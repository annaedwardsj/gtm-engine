"use client";

import { useState } from "react";
import { ICP, SegmentState } from "@/types/icp";
import ConfidencePill from "./ConfidencePill";

interface Props {
  icp: ICP;
}

const SENIORITY_COLOR: Record<string, string> = {
  "C-suite": "bg-purple-100 text-purple-700",
  VP: "bg-blue-100 text-blue-700",
  Director: "bg-sky-100 text-sky-700",
  Manager: "bg-teal-100 text-teal-700",
  IC: "bg-slate-100 text-slate-600",
};

function Section({ title, children }: { title: string; children: React.ReactNode }) {
  return (
    <div className="space-y-2">
      <h3 className="text-xs font-semibold uppercase tracking-widest text-slate-400">{title}</h3>
      {children}
    </div>
  );
}

export default function ICPCard({ icp }: Props) {
  const [segmentStates, setSegmentStates] = useState<Record<string, SegmentState>>(() =>
    Object.fromEntries(icp.expansionSegments.map((s) => [s.id, "pending"]))
  );
  const [editing, setEditing] = useState<string | null>(null);
  const [editValues, setEditValues] = useState<Record<string, string>>(() =>
    Object.fromEntries(icp.expansionSegments.map((s) => [s.id, s.name]))
  );

  const setState = (id: string, state: SegmentState) =>
    setSegmentStates((prev) => ({ ...prev, [id]: state }));

  return (
    <div className="rounded-2xl border border-slate-200 bg-white shadow-sm divide-y divide-slate-100">
      {/* Header */}
      <div className="px-6 py-4">
        <h2 className="text-lg font-semibold text-slate-900">Ideal Customer Profile</h2>
        <p className="text-sm text-slate-500 mt-0.5">Generated by Claude — review and refine</p>
      </div>

      <div className="px-6 py-5 grid grid-cols-1 md:grid-cols-2 gap-6">
        {/* Target Industries */}
        <Section title="Target Industries">
          <div className="flex flex-wrap gap-2">
            {icp.targetIndustries.map((ind) => (
              <span key={ind.name} className="inline-flex items-center gap-1.5 rounded-lg border border-slate-200 bg-slate-50 px-3 py-1 text-sm text-slate-700">
                {ind.name}
                <ConfidencePill value={ind.confidence} />
              </span>
            ))}
          </div>
        </Section>

        {/* Company Size */}
        <Section title="Company Size">
          <div className="flex items-center gap-3">
            <div className="rounded-xl bg-indigo-50 border border-indigo-100 px-4 py-2">
              <span className="text-2xl font-bold text-indigo-700">
                {icp.companySizeRange.min.toLocaleString()}–{icp.companySizeRange.max.toLocaleString()}
              </span>
              <span className="ml-1.5 text-sm text-indigo-500">{icp.companySizeRange.unit}</span>
            </div>
            <ConfidencePill value={icp.companySizeRange.confidence} />
          </div>
        </Section>

        {/* Buyer Titles */}
        <Section title="Buyer Personas">
          <div className="space-y-1.5">
            {icp.buyerTitles.map((bt) => (
              <div key={bt.title} className="flex items-center justify-between gap-2">
                <div className="flex items-center gap-2">
                  <span className={`rounded-full px-2 py-0.5 text-xs font-medium ${SENIORITY_COLOR[bt.seniority] ?? "bg-slate-100 text-slate-600"}`}>
                    {bt.seniority}
                  </span>
                  <span className="text-sm text-slate-700">{bt.title}</span>
                </div>
                <ConfidencePill value={bt.confidence} />
              </div>
            ))}
          </div>
        </Section>

        {/* Trigger Events */}
        <Section title="Trigger Events">
          <ul className="space-y-1.5">
            {icp.triggerEvents.map((te) => (
              <li key={te.event} className="flex items-center justify-between gap-2">
                <span className="flex items-center gap-2 text-sm text-slate-700">
                  <span className="size-1.5 rounded-full bg-indigo-400 shrink-0" />
                  {te.event}
                </span>
                <ConfidencePill value={te.confidence} />
              </li>
            ))}
          </ul>
        </Section>
      </div>

      {/* Expansion Segments */}
      <div className="px-6 py-5 space-y-3">
        <h3 className="text-xs font-semibold uppercase tracking-widest text-slate-400">Expansion Segments</h3>
        <div className="grid gap-3 sm:grid-cols-2 lg:grid-cols-3">
          {icp.expansionSegments.map((seg) => {
            const state = segmentStates[seg.id];
            return (
              <div
                key={seg.id}
                className={`rounded-xl border p-4 transition-all ${
                  state === "accepted"
                    ? "border-emerald-300 bg-emerald-50"
                    : state === "dismissed"
                    ? "border-slate-200 bg-slate-50 opacity-50"
                    : "border-slate-200 bg-white"
                }`}
              >
                <div className="flex items-start justify-between gap-2 mb-1.5">
                  {editing === seg.id ? (
                    <input
                      autoFocus
                      value={editValues[seg.id]}
                      onChange={(e) => setEditValues((prev) => ({ ...prev, [seg.id]: e.target.value }))}
                      onBlur={() => setEditing(null)}
                      onKeyDown={(e) => e.key === "Enter" && setEditing(null)}
                      className="flex-1 rounded border border-indigo-300 px-2 py-0.5 text-sm font-semibold text-slate-900 focus:outline-none focus:ring-2 focus:ring-indigo-400"
                    />
                  ) : (
                    <p className="text-sm font-semibold text-slate-900">{editValues[seg.id]}</p>
                  )}
                  <ConfidencePill value={seg.confidence} />
                </div>
                <p className="text-xs text-slate-500 leading-relaxed mb-3">{seg.rationale}</p>

                {state !== "dismissed" && (
                  <div className="flex gap-1.5">
                    {state === "pending" && (
                      <button
                        onClick={() => setState(seg.id, "accepted")}
                        className="flex-1 rounded-lg bg-emerald-600 px-2 py-1 text-xs font-medium text-white hover:bg-emerald-700 transition-colors"
                      >
                        Accept
                      </button>
                    )}
                    {state === "accepted" && (
                      <button
                        onClick={() => setState(seg.id, "pending")}
                        className="flex-1 rounded-lg bg-slate-200 px-2 py-1 text-xs font-medium text-slate-600 hover:bg-slate-300 transition-colors"
                      >
                        Undo
                      </button>
                    )}
                    <button
                      onClick={() => setEditing(seg.id)}
                      className="flex-1 rounded-lg border border-slate-200 px-2 py-1 text-xs font-medium text-slate-600 hover:bg-slate-50 transition-colors"
                    >
                      Edit
                    </button>
                    <button
                      onClick={() => setState(seg.id, "dismissed")}
                      className="rounded-lg border border-slate-200 px-2 py-1 text-xs font-medium text-slate-400 hover:bg-slate-50 transition-colors"
                    >
                      ✕
                    </button>
                  </div>
                )}
                {state === "dismissed" && (
                  <button
                    onClick={() => setState(seg.id, "pending")}
                    className="text-xs text-slate-400 hover:text-slate-600 underline"
                  >
                    Restore
                  </button>
                )}
              </div>
            );
          })}
        </div>
      </div>
    </div>
  );
}
